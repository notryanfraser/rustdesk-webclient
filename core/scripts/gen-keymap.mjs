// Generates src/input/keymap.gen.ts from the vendored rdev keycode tables (vendor/rdev/keycodes,
// rustdesk-org/rdev 0904f23, the version rustdesk 1.5.3 pins). Run: node scripts/gen-keymap.mjs
//
// Upstream's own tables, joined, give what a browser needs for map mode:
// chrome.rs KeyboardEvent.code <-> rdev Key
// windows.rs rdev Key -> (virtual key, scancode); map mode sends the scancode
// linux.rs rdev Key -> X11 (Xorg) keycode
// macos.rs rdev Key -> kVK_* virtual keycode (values in macos_virtual_keycodes.rs)
// Only the decl_keycodes! invocation is read; comments are stripped first, which also drops
// entries upstream has commented out. The output is deterministic (upstream order).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "vendor/rdev/keycodes");
const read = (f) => readFileSync(join(dir, f), "utf8");
const stripComments = (s) =>
  s.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "");

/** Tokens of the `decl_keycodes! { ... }` / `decl_keycodes!( ... )` invocation body. */
function invocation(src) {
  const s = stripComments(src);
  const at = s.search(/decl_keycodes!\s*[({]/);
  if (at < 0) throw new Error("no decl_keycodes! invocation");
  const open = s.indexOf(s.slice(at).match(/[({]/)[0], at);
  const close = { "(": ")", "{": "}" }[s[open]];
  let depth = 0;
  let end = open;
  for (; end < s.length; end++) {
    if (s[end] === s[open]) depth++;
    else if (s[end] === close && --depth === 0) break;
  }
  return s
    .slice(open + 1, end)
    .split(",")
    .map((t) => t.trim())
    .filter((t) => t !== "");
}
const groups = (tokens, n) => {
  if (tokens.length % n)
    throw new Error(`token count ${tokens.length} not a multiple of ${n}`);
  const out = [];
  for (let i = 0; i < tokens.length; i += n) out.push(tokens.slice(i, i + n));
  return out;
};
const num = (t) => {
  if (!/^(0x[0-9a-fA-F]+|\d+)$/.test(t)) throw new Error(`not a number: ${t}`);
  return Number(t);
};

const kvk = {};
for (const m of stripComments(read("macos_virtual_keycodes.rs")).matchAll(
  /pub const (kVK_\w+)\s*:\s*\w+\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*;/g,
))
  kvk[m[1]] = Number(m[2]);

const codeToKey = {};
for (const [key, code] of groups(invocation(read("chrome.rs")), 2)) {
  const c = JSON.parse(code);
  if (c !== "" && !(c in codeToKey)) codeToKey[c] = key; // key_from_code: first match wins
}
const platform = {};
const put = (key, field, value) => ((platform[key] ??= {})[field] ??= value);
for (const [key, , scancode] of groups(invocation(read("windows.rs")), 3))
  put(key, "win", num(scancode));
for (const [key, code] of groups(invocation(read("linux.rs")), 2))
  put(key, "linux", num(code));
for (const [key, name] of groups(invocation(read("macos.rs")), 2)) {
  if (!(name in kvk)) throw new Error(`unknown macOS constant ${name}`);
  put(key, "mac", kvk[name]);
}

const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
const lines = [
  "// GENERATED by scripts/gen-keymap.mjs from vendor/rdev/keycodes (rustdesk-org/rdev 0904f23,",
  "// MIT, pinned by rustdesk 1.5.3). Do not edit; re-vendor and regenerate.",
  "",
  "/** KeyboardEvent.code -> rdev Key name (rdev src/keycodes/chrome.rs). */",
  "export const CODE_TO_RDEV_KEY: Readonly<Record<string, string>> = {",
  ...Object.entries(codeToKey).map(
    ([c, k]) => `  ${JSON.stringify(c)}: ${JSON.stringify(k)},`,
  ),
  "};",
  "",
  "/** Native key code per peer platform, by rdev Key name. win = scancode (0xE0xx = extended). */",
  "export const RDEV_KEY_CODES: Readonly<",
  "  Record<string, { win?: number; linux?: number; mac?: number }>",
  "> = {",
  ...Object.entries(platform).map(([k, v]) => {
    const parts = [];
    if (v.win !== undefined) parts.push(`win: ${hex(v.win)}`);
    if (v.linux !== undefined) parts.push(`linux: ${v.linux}`);
    if (v.mac !== undefined) parts.push(`mac: ${v.mac}`);
    return `  ${k}: { ${parts.join(", ")} },`;
  }),
  "};",
  "",
];
writeFileSync(join(root, "src/input/keymap.gen.ts"), lines.join("\n"));
console.log(
  `keymap: ${Object.keys(codeToKey).length} browser codes, ${Object.keys(platform).length} rdev keys`,
);
